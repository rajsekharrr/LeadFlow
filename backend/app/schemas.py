"""
Pydantic v2 schemas for LeadFlow API.

These schemas define the API contract - what data is accepted in requests
and what data is returned in responses. They are separate from the SQLAlchemy
ORM models to allow independent evolution of the database schema and API.
"""
from datetime import datetime
from enum import Enum
from typing import Optional
from pydantic import BaseModel, Field, ConfigDict


class LeadStatus(str, Enum):
    """
    Valid status values for a lead.

    Inheriting from both str and Enum allows these values to be serialized
    as plain strings in JSON while still providing validation.
    """
    NEW = "New"
    CONTACTED = "Contacted"
    QUALIFIED = "Qualified"
    PROPOSAL_SENT = "Proposal Sent"
    WON = "Won"
    LOST = "Lost"


# ==================== Lead Schemas ====================

class CreateLeadRequest(BaseModel):
    """
    Request schema for creating a new lead.

    Only includes fields that the client can set during creation.
    Fields like id, timestamps are auto-generated by the system.
    """
    name: str = Field(..., min_length=1, description="Lead's full name (required)")
    company: Optional[str] = Field(None, description="Company name (optional)")
    phone: Optional[str] = Field(None, description="Phone number (optional)")
    status: LeadStatus = Field(
        default=LeadStatus.NEW,
        description="Initial status (defaults to 'New')"
    )

    model_config = ConfigDict(
        json_schema_extra={
            "example": {
                "name": "John Smith",
                "company": "Acme Corp",
                "phone": "+1 555-0123",
                "status": "New"
            }
        }
    )


class UpdateLeadRequest(BaseModel):
    """
    Request schema for updating a lead.

    All fields are optional - only send what needs to be changed.
    Designed for PATCH semantics (partial update).
    """
    status: Optional[LeadStatus] = Field(None, description="New status")
    follow_up_at: Optional[datetime] = Field(None, description="Next follow-up date/time")

    model_config = ConfigDict(
        json_schema_extra={
            "example": {
                "status": "Contacted",
                "follow_up_at": "2026-10-20T14:00:00"
            }
        }
    )


class LeadResponse(BaseModel):
    """
    Response schema for a lead.

    Includes all database fields plus computed fields that are assembled
    by the CRUD layer (last_note, last_discussion_at, discussion_count).
    These computed fields are NOT stored in the database.
    """
    id: str
    name: str
    company: Optional[str]
    phone: Optional[str]
    status: LeadStatus
    follow_up_at: Optional[datetime]
    created_at: datetime
    updated_at: datetime

    # Computed fields - assembled by CRUD layer, not stored in database
    last_note: Optional[str] = Field(
        None,
        description="Most recent discussion note (or None if no discussions)"
    )
    last_discussion_at: Optional[datetime] = Field(
        None,
        description="Timestamp of most recent discussion"
    )
    discussion_count: int = Field(
        default=0,
        description="Total number of discussions for this lead"
    )

    # Enable reading from SQLAlchemy ORM objects
    # from_attributes=True was orm_mode=True in Pydantic v1
    model_config = ConfigDict(from_attributes=True)


# ==================== Discussion Schemas ====================

class CreateDiscussionRequest(BaseModel):
    """
    Request schema for creating a discussion.

    If follow_up_at is provided, the parent lead's follow_up_at
    field will also be updated (handled in CRUD layer).
    """
    note: str = Field(..., min_length=1, description="Discussion content (required)")
    follow_up_at: Optional[datetime] = Field(
        None,
        description="Optional follow-up date/time (also updates parent lead if set)"
    )

    model_config = ConfigDict(
        json_schema_extra={
            "example": {
                "note": "Had a great call. Client is interested in our premium package.",
                "follow_up_at": "2026-10-21T10:00:00"
            }
        }
    )


class DiscussionResponse(BaseModel):
    """
    Response schema for a discussion.

    Includes all fields from the database.
    """
    id: str
    lead_id: str
    note: str
    follow_up_at: Optional[datetime]
    created_at: datetime

    # Enable reading from SQLAlchemy ORM objects
    model_config = ConfigDict(from_attributes=True)


# ==================== Type Aliases for Documentation ====================

# These type hints make route signatures more readable
LeadList = list[LeadResponse]
DiscussionList = list[DiscussionResponse]
